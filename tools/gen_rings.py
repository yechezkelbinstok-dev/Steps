#!/usr/bin/env python3
"""Generates the widget's progress-ring vector drawables.

Widgets can't draw arbitrary arcs, and bitmaps bloat widget updates, so each whole percent
gets its own tiny vector arc, plus a full gold ring for a met goal (ring_goal) and a plain
track (ring_track) that the widget tints to the card's tone:
 - ring_p001..ring_p100: plain white, tinted at runtime (the soft style)
 - ring_f001..ring_f100: white fading in toward the tip, tinted at runtime (the fade style;
   tinting keeps the alpha)
 - ring_v001..ring_v100: aqua -> blue (the vivid style)
 - ring_l001..ring_l100: past the goal, the next gold lap, deepening to amber
 - ring_s001..ring_s100: the soft shadow a lap casts ahead of its tip onto the ring beneath,
   so you can see where the overlap ends

Gradient arcs run their sweep from the start of the arc to its tip, so a short arc still shows
the whole blend. Each arc is drawn starting at 3 o'clock inside a group rotated -90 degrees,
which lines the sweep gradient up with 12 o'clock.

Run from the repo root: python3 tools/gen_rings.py
"""
import math
import os

OUT = "app/src/main/res/drawable"
KT = "app/src/main/java/app/wakesteps/widget/RingDrawables.kt"
SIZE, STROKE = 100, 11
R = (SIZE - STROKE) / 2
C = SIZE / 2

PLAIN = "#FFFFFFFF"                              # tinted at runtime
VIVID_START, VIVID_END = "#FF2BE7C8", "#FF3A8DFF"  # aqua -> blue
FADE_START, FADE_END = "#6BFFFFFF", "#FFFFFFFF"  # faint -> solid, tinted at runtime
GOAL_START, GOAL_END = "#FFFFE082", "#FFFF9F1C"  # light gold -> amber
LAP_END = "#FFFF8A00"                            # a lap deepens past the full ring's amber

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_rings.py. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{s}dp" android:height="{s}dp"
    android:viewportWidth="{s}" android:viewportHeight="{s}">
""".format(s=SIZE)

FULL = f"M{C + R},{C} A{R},{R} 0 1,1 {C - R},{C} A{R},{R} 0 1,1 {C + R},{C}"


def arc(fraction):
    """Arc from 3 o'clock, clockwise (screen coordinates), covering `fraction` of the circle."""
    if fraction >= 1:
        return FULL
    a = math.radians(360 * fraction)
    x, y = C + R * math.cos(a), C + R * math.sin(a)
    large = 1 if fraction > 0.5 else 0
    return f"M{C + R},{C} A{R},{R} 0 {large},1 {x:.2f},{y:.2f}"


def gradient_path(d, start, end, tip):
    # Back to the start colour after the tip so the round cap at 12 o'clock, which pokes
    # just "behind" the start of the sweep, doesn't pick up the end colour.
    if tip >= 1:
        # A closed ring: blend out and back so the colours meet seamlessly at the top.
        items = [(0, start), (0.5, end), (1, start)]
    else:
        items = [(0, start), (tip, end), (1, start)]
    stops = "\n".join(
        f'                    <item android:offset="{o:.3f}" android:color="{c}" />' for o, c in items
    )
    return f"""    <group android:rotation="-90" android:pivotX="{C}" android:pivotY="{C}">
        <path android:strokeWidth="{STROKE}" android:strokeLineCap="round" android:pathData="{d}">
            <aapt:attr name="android:strokeColor">
                <gradient android:type="sweep" android:centerX="{C}" android:centerY="{C}">
{stops}
                </gradient>
            </aapt:attr>
        </path>
    </group>
"""


def shadow(fraction):
    """A dark blur just ahead of the tip of an arc covering `fraction`, kept within the ring."""
    a = math.radians(360 * fraction) + 3 / R  # a little past the tip, under the round cap
    x, y = C + R * math.cos(a), C + R * math.sin(a)
    outer, inner = R + STROKE / 2, R - STROKE / 2
    # Outer circle clockwise, inner counter-clockwise: a ring-shaped clip (nonzero winding).
    ring = (f"M{C + outer},{C} A{outer},{outer} 0 1,1 {C - outer},{C} A{outer},{outer} 0 1,1 {C + outer},{C} Z "
            f"M{C + inner},{C} A{inner},{inner} 0 1,0 {C - inner},{C} A{inner},{inner} 0 1,0 {C + inner},{C} Z")
    r = STROKE
    blob = f"M{x + r:.2f},{y:.2f} A{r},{r} 0 1,1 {x - r:.2f},{y:.2f} A{r},{r} 0 1,1 {x + r:.2f},{y:.2f} Z"
    return f"""    <group android:rotation="-90" android:pivotX="{C}" android:pivotY="{C}">
        <clip-path android:pathData="{ring}" />
        <path android:pathData="{blob}">
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="{x:.2f}" android:centerY="{y:.2f}" android:gradientRadius="{r}">
                    <item android:offset="0" android:color="#73000000" />
                    <item android:offset="0.55" android:color="#33000000" />
                    <item android:offset="1" android:color="#00000000" />
                </gradient>
            </aapt:attr>
        </path>
    </group>
"""


def write(name, body):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(HEADER + body + "</vector>\n")


# Opaque white, tinted with the card's track colour at runtime.
write("ring_track.xml",
      f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{STROKE}" android:pathData="{FULL}" />\n')
for p in range(1, 101):
    write(f"ring_p{p:03d}.xml",
          f'    <group android:rotation="-90" android:pivotX="{C}" android:pivotY="{C}">\n'
          f'        <path android:strokeColor="{PLAIN}" android:strokeWidth="{STROKE}" android:strokeLineCap="round"\n'
          f'            android:pathData="{arc(p / 100)}" />\n'
          f'    </group>\n')
write("ring_goal.xml", gradient_path(FULL, GOAL_START, GOAL_END, 1.0))
for p in range(1, 101):
    write(f"ring_f{p:03d}.xml", gradient_path(arc(p / 100), FADE_START, FADE_END, p / 100))
    write(f"ring_v{p:03d}.xml", gradient_path(arc(p / 100), VIVID_START, VIVID_END, p / 100))
    write(f"ring_l{p:03d}.xml", gradient_path(arc(p / 100), GOAL_START, LAP_END, p / 100))
    write(f"ring_s{p:03d}.xml", shadow(p / 100))

with open(KT, "w") as f:
    f.write("// Generated by tools/gen_rings.py. Do not edit.\n")
    f.write("package app.wakesteps.widget\n\nimport app.wakesteps.R\n\n")
    for name, prefix, what in [
        ("RING_ARCS", "ring_p", "a plain white arc"),
        ("FADE_ARCS", "ring_f", "a fading white arc"),
        ("VIVID_ARCS", "ring_v", "an aqua-to-blue arc"),
        ("LAP_ARCS", "ring_l", "a gold lap"),
        ("LAP_SHADOWS", "ring_s", "the shadow ahead of the tip of a lap"),
    ]:
        f.write(f"\n/** Index n (1..100) is {what} covering n% of the ring; index 0 is unused. */\n")
        f.write(f"internal val {name} = intArrayOf(\n    0,\n")
        for p in range(1, 101):
            f.write(f"    R.drawable.{prefix}{p:03d},\n")
        f.write(")\n")
